export function fighterGroundOffset(time: number, height: number) {
  if (!Number.isFinite(time) || !Number.isFinite(height) || height <= 0) {
    throw new Error("ETFC fighter grounding requires a finite time and positive height.");
  }
  const phase = Math.min(1, Math.max(0, time / FIGHTER_GROUNDING.duration));
  const sample = phase * (CONTACT_HEIGHTS.length - 1);
  const index = Math.min(Math.floor(sample), CONTACT_HEIGHTS.length - 2);
  const contact = CONTACT_HEIGHTS[index] + (CONTACT_HEIGHTS[index + 1] - CONTACT_HEIGHTS[index]) * (sample - index);
  return 0.003 - contact * height / FIGHTER_GROUNDING.normalizedHeight;
}
